import type { CellGrid } from '../core/grid';
import type { Font } from './font';
import type { CapturedSequence } from './sequence';

/**
 * Arduino-ready dump of the current frame + font (ST7796S, RGB565).
 * Draw loop on the MCU: for each entry → setAddrWindow(col*CW, row*CH+Y0, CW, CH) → push glyph bits.
 */
export function exportCHeader(grid: CellGrid, font: Font, dirty?: Int32Array, dirtyN?: number): string {
  const cells: number[] = [];
  if (dirty && dirtyN !== undefined && dirtyN < grid.size) for (let k = 0; k < dirtyN; k++) cells.push(dirty[k]);
  else for (let i = 0; i < grid.size; i++) if (grid.chr[i] !== 32) cells.push(i);

  const L: string[] = [];
  L.push('// Usagi ASCII frame — generated by usagi-ascii-pet');
  L.push(`#define USAGI_COLS ${grid.cols}`, `#define USAGI_ROWS ${grid.rows}`);
  L.push(`#define USAGI_CW ${grid.cw}`, `#define USAGI_CH ${grid.ch}`, `#define USAGI_Y0 ${grid.oy}`);
  L.push(`#define USAGI_CELLS ${cells.length}`, '');
  L.push('struct UsagiCell { uint8_t col; uint8_t row; char ch; uint16_t rgb565; };');
  L.push('static const UsagiCell USAGI_FRAME[USAGI_CELLS] PROGMEM = {');
  let line = '  ';
  for (const i of cells) {
    const r = (i / grid.cols) | 0, c = i - r * grid.cols;
    const ch = grid.chr[i];
    const lit = ch === 39 ? "'\\''" : ch === 92 ? "'\\\\'" : `'${String.fromCharCode(ch)}'`;
    line += `{${c},${r},${lit},0x${grid.fg[i].toString(16).padStart(4, '0')}}, `;
    if (line.length > 96) { L.push(line.trimEnd()); line = '  '; }
  }
  if (line.trim()) L.push(line.trimEnd());
  L.push('};', '');

  // font: one byte per row, bit 7 = leftmost pixel (cw <= 8)
  L.push(`// ${font.cw}x${font.ch} 1-bpp font, ASCII 32..126 (${font.ch} bytes per glyph)`);
  L.push(`static const uint8_t USAGI_FONT[95][${font.ch}] PROGMEM = {`);
  for (let g = 0; g < 95; g++) {
    const rows: string[] = [];
    for (let y = 0; y < font.ch; y++) {
      let v = 0;
      for (let x = 0; x < font.cw; x++) if (font.bits[(g * font.ch + y) * font.cw + x]) v |= 0x80 >> x;
      rows.push('0x' + v.toString(16).padStart(2, '0'));
    }
    L.push(`  {${rows.join(',')}}, // '${g + 32 === 92 ? '\\\\' : String.fromCharCode(g + 32)}'`);
  }
  L.push('};');
  return L.join('\n');
}

interface EncodedFrame { offset: number; bytes: number; dirty: number }

/**
 * Animation stream: [cell:u16, tag:u8, payload...] records, 0xffff terminator.
 * tag 1..127 is a literal run of (char,u16 RGB565); tag 0x80..0xff repeats one
 * cell value. Frames after a clip keyframe contain only changed cells. Runs
 * never cross a display row, allowing one ST7796 window per run.
 */
export function exportAnimationCHeader(seq: CapturedSequence, font: Font): string {
  const data: number[] = [];
  const meta: EncodedFrame[] = [];
  const clips: Array<{ first: number; count: number; fps: number; loop: boolean; name: string }> = [];
  const push16 = (v: number) => { data.push(v & 255, v >>> 8); };
  for (const clip of seq.clips) {
    const first = meta.length;
    let prev: typeof clip.frames[number] | undefined;
    for (const frame of clip.frames) {
      const start = data.length;
      const changed: number[] = [];
      for (let i = 0; i < frame.chr.length; i++)
        if (!prev || frame.chr[i] !== prev.chr[i] || (frame.chr[i] !== 32 && frame.fg[i] !== prev.fg[i])) changed.push(i);
      let k = 0;
      while (k < changed.length) {
        const runStart = changed[k];
        let end = k + 1;
        while (end < changed.length && end - k < 127 && changed[end] === changed[end - 1] + 1 &&
               Math.floor(changed[end] / seq.cols) === Math.floor(runStart / seq.cols)) end++;
        const n = end - k;
        let same = n >= 3;
        for (let q = k + 1; same && q < end; q++)
          same = frame.chr[changed[q]] === frame.chr[runStart] && frame.fg[changed[q]] === frame.fg[runStart];
        push16(runStart);
        data.push(same ? 0x80 | n : n);
        if (same) {
          data.push(frame.chr[runStart]); push16(frame.fg[runStart]);
        } else {
          for (let q = k; q < end; q++) { const i = changed[q]; data.push(frame.chr[i]); push16(frame.fg[i]); }
        }
        k = end;
      }
      push16(0xffff);
      meta.push({ offset: start, bytes: data.length - start, dirty: changed.length });
      prev = frame;
    }
    clips.push({ first, count: meta.length - first, fps: clip.fps, loop: clip.loop, name: clip.name });
  }

  const L: string[] = [];
  L.push('// Generated from the original usagi-ascii-pet renderer. Do not hand-edit.', '#pragma once', '#include <Arduino.h>', '');
  L.push(`#define USAGI_COLS ${seq.cols}`, `#define USAGI_ROWS ${seq.rows}`, `#define USAGI_CW ${seq.cw}`, `#define USAGI_CH ${seq.ch}`, `#define USAGI_Y0 ${seq.oy}`);
  L.push(`#define USAGI_FRAME_COUNT ${meta.length}`, `#define USAGI_CLIP_COUNT ${clips.length}`, `#define USAGI_DATA_BYTES ${data.length}`, '');
  L.push('struct UsagiFrameInfo { uint32_t offset; uint16_t bytes; uint16_t dirty; };');
  L.push('struct UsagiClipInfo { uint16_t first; uint16_t count; uint8_t fps; uint8_t loop; };');
  L.push('enum UsagiClip : uint8_t { USAGI_INTRO, USAGI_IDLE, USAGI_THINKING, USAGI_HAPPY, USAGI_SLEEPING, USAGI_ERROR, USAGI_EXCITED };', '');
  L.push('static const UsagiClipInfo USAGI_CLIPS[USAGI_CLIP_COUNT] PROGMEM = {');
  for (const c of clips) L.push(`  {${c.first},${c.count},${c.fps},${c.loop ? 1 : 0}}, // ${c.name}`);
  L.push('};', 'static const UsagiFrameInfo USAGI_FRAMES[USAGI_FRAME_COUNT] PROGMEM = {');
  for (const f of meta) L.push(`  {${f.offset}UL,${f.bytes},${f.dirty}},`);
  L.push('};', `static const uint8_t USAGI_DATA[USAGI_DATA_BYTES] PROGMEM = {`);
  for (let i = 0; i < data.length; i += 24) L.push('  ' + data.slice(i, i + 24).map(v => '0x' + v.toString(16).padStart(2, '0')).join(',') + ',');
  L.push('};', `static const uint8_t USAGI_FONT[95][${font.ch}] PROGMEM = {`);
  for (let g = 0; g < 95; g++) {
    const rows: string[] = [];
    for (let y = 0; y < font.ch; y++) {
      let v = 0;
      for (let x = 0; x < font.cw; x++) if (font.bits[(g * font.ch + y) * font.cw + x]) v |= 0x80 >> x;
      rows.push('0x' + v.toString(16).padStart(2, '0'));
    }
    L.push(`  {${rows.join(',')}},`);
  }
  L.push('};', '');
  return L.join('\n');
}
