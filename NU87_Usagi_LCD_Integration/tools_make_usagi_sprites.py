#!/usr/bin/env python3
"""Convert the 6 original Usagi illustrations (sprite_src/, real alpha) into usagi_sprites.h.
Each is cropped to its alpha bounding box, scaled so ear tip -> foot spans the same height, bottom/centre aligned in a fixed
SW x SH canvas, composited on the Home background colour (so no mask is needed), quantised to <=64 colours (no dithering,
outlines preserved) and run-length encoded. Source art is never redrawn or recoloured beyond that quantisation."""
from pathlib import Path
from PIL import Image
HERE = Path(__file__).resolve().parent
SW, SH, TOP, BOT = 184, 180, 2, 178           # canvas; ear tip at y=TOP, feet at y=BOT
BG = (248, 248, 248)                          # UI_BG
NAMES = [("IDLE", "idle.webp"), ("NOTIFY", "notify.webp"), ("THINKING", "thinking.png"), ("HAPPY", "happy.png"), ("SAD", "sad.png"), ("SLEEPING", "sleeping.png")]

def rgb565(c): return ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)

out = ["// Generated by tools_make_usagi_sprites.py from the original illustrations. Do not hand-edit.", "#pragma once", "#include <Arduino.h>",
       f"#define SPRITE_W {SW}", f"#define SPRITE_H {SH}", f"#define SPRITE_COUNT {len(NAMES)}",
       "enum SpriteId : uint8_t { " + ", ".join(f"SPR_{n}" for n, _ in NAMES) + " };", ""]
data, offs, total = bytearray(), [], 0
sheet = Image.new("RGB", (SW * 3, SH * 2), BG)
for n, f in NAMES:
    im = Image.open(HERE / "sprite_src" / f).convert("RGBA")
    a = im.getchannel("A"); bbox = a.point(lambda v: 255 if v > 8 else 0).getbbox()
    im = im.crop(bbox); h = BOT - TOP; w = round(im.width * h / im.height)
    assert w <= SW - 2, (n, w)
    flat = Image.new("RGBA", im.size, BG + (255,)); flat.alpha_composite(im)        # composite at full resolution, then scale
    flat = flat.convert("RGB").resize((w, h), Image.LANCZOS)
    canvas = Image.new("RGB", (SW, SH), BG); canvas.paste(flat, ((SW - w) // 2, TOP))
    q = canvas.quantize(colors=64, method=Image.MEDIANCUT, dither=Image.NONE)
    pal = q.getpalette()[:192]; ncol = len(pal) // 3
    pal565 = [rgb565(tuple(pal[i * 3:i * 3 + 3])) for i in range(ncol)]
    # background must stay exactly UI_BG so the canvas melts into the screen
    bgi = q.getpixel((0, 0)); pal565[bgi] = rgb565(BG)
    sheet.paste(q.convert("RGB"), (len(offs) % 3 * SW, len(offs) // 3 * SH))
    px = list(q.getdata()); stream = bytearray()
    i = 0
    while i < len(px):
        r = 1
        while i + r < len(px) and px[i + r] == px[i] and r < 255: r += 1
        stream += bytes([r, px[i]]); i += r
    offs.append((len(data), len(stream), pal565 + [0] * (64 - ncol)))
    data += stream; total += len(stream)
    print(f"{n:9s} src {Image.open(HERE/'sprite_src'/f).size} bbox {bbox} -> {w}x{h} colours {ncol} rle {len(stream)} B")
out.append(f"static const uint16_t SPRITE_PAL[SPRITE_COUNT][64] PROGMEM = {{")
for _, _, p in offs: out.append("  {" + ",".join(f"0x{c:04X}" for c in p) + "},")
out.append("};")
out.append(f"static const uint32_t SPRITE_OFF[SPRITE_COUNT + 1] PROGMEM = {{" + ",".join(str(o[0]) for o in offs) + f",{len(data)}" + "};")
out.append(f"static const uint8_t SPRITE_DATA[{len(data)}] PROGMEM = {{")
for i in range(0, len(data), 32): out.append("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 32]) + ",")
out.append("};")
(HERE / "usagi_sprites.h").write_text("\n".join(out) + "\n")
print("total flash ~", len(data) + len(offs) * 128, "bytes")
sheet.save("/tmp/usagi_sheet.png")
