#!/usr/bin/env python3
"""Generate the MCU-side proportional 4-bpp UI font from Pretendard SemiBold.

Each glyph is stored in a fixed CW x CH cell (cell = widest glyph) but also
has a per-glyph advance (UI_xx_ADV) so text is proportional and measurable.
Coverage is gamma-boosted for contrast on the LCD. Re-run after changing SPECS.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent / "ui_font_4bpp.h"
FONT = Path.home() / "Library/Fonts/Pretendard-SemiBold.ttf"
EXTRA = "\N{DEGREE SIGN}\N{MIDDLE DOT}\N{RIGHTWARDS ARROW}"
CHARS = ''.join(chr(x) for x in range(32, 127)) + EXTRA
GAMMA = 0.72
# label, pixel size, cell height, extra letter-spacing px
SPECS = [("SM", 12, 16, 1), ("MD", 14, 18, 1), ("LG", 18, 22, 1), ("XL", 32, 38, 1)]

def build(px, ch, spacing):
    font = ImageFont.truetype(str(FONT), px)
    base = round(ch * 0.76)
    adv = [max(2, round(font.getlength(c)) + spacing) for c in CHARS]
    cw = max(adv)
    blob = []
    for c, a in zip(CHARS, adv):
        im = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(im).text((0, base), c, fill=255, font=font, anchor="ls")
        vals = [round(15 * (v / 255) ** GAMMA) for v in im.getdata()]
        if len(vals) & 1: vals.append(0)
        blob.extend((vals[i] << 4) | vals[i + 1] for i in range(0, len(vals), 2))
    return cw, adv, blob

with OUT.open("w") as f:
    f.write("// Generated by tools_make_ui_font.py (Pretendard SemiBold); 98 glyphs: ASCII 32..126, degree, middot, arrow.\n#pragma once\n#include <Arduino.h>\n\n")
    for label, px, ch, sp in SPECS:
        cw, adv, b = build(px, ch, sp)
        f.write(f"#define UI_{label}_CW {cw}\n#define UI_{label}_CH {ch}\n")
        f.write(f"static const uint8_t UI_{label}_ADV[{len(adv)}] PROGMEM = {{" + ",".join(map(str, adv)) + "};\n")
        f.write(f"static const uint8_t UI_{label}_4BPP[{len(b)}] PROGMEM = {{\n")
        for i in range(0, len(b), 24): f.write("  " + ",".join(f"0x{x:02X}" for x in b[i:i+24]) + ",\n")
        f.write("};\n\n")
        print(label, px, "cell", cw, "x", ch, "digit adv", adv[ord('0') - 32], "W adv", adv[ord('W') - 32])
