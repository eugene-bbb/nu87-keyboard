#!/usr/bin/env python3
"""KS X 1001 Hangul (2350 syllables) for the SM and MD UI fonts, same Pretendard SemiBold rendering as tools_make_ui_font.py.
Output: ui_hangul_4bpp.h. Syllables outside this set are drawn as '?'."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
OUT = Path(__file__).resolve().parent / "ui_hangul_4bpp.h"
FONT = Path.home() / "Library/Fonts/Pretendard-SemiBold.ttf"
GAMMA = 0.72
SPECS = [("SM", 12, 13, 16), ("MD", 14, 15, 18)]       # label, px, cell width (== existing UI_xx_CW), cell height
chars = []
for hi in range(0xB0, 0xC9):
    for lo in range(0xA1, 0xFF):
        try: chars.append(bytes([hi, lo]).decode("euc-kr"))
        except UnicodeDecodeError: pass
chars = sorted(set(c for c in chars if 0xAC00 <= ord(c) <= 0xD7A3))
with OUT.open("w") as f:
    f.write(f"// Generated by tools_make_hangul_font.py: {len(chars)} KS X 1001 Hangul syllables (SM, MD).\n#pragma once\n#include <Arduino.h>\n")
    f.write(f"#define UI_HANGUL_N {len(chars)}\nstatic const uint16_t UI_HANGUL_CP[UI_HANGUL_N] PROGMEM = {{" + ",".join(str(ord(c)) for c in chars) + "};\n")
    for label, px, cw, ch in SPECS:
        font = ImageFont.truetype(str(FONT), px); base = round(ch * 0.76); blob = []
        for c in chars:
            im = Image.new("L", (cw, ch), 0); ImageDraw.Draw(im).text((0, base), c, fill=255, font=font, anchor="ls")
            vals = [round(15 * (v / 255) ** GAMMA) for v in im.getdata()]
            if len(vals) & 1: vals.append(0)
            blob.extend((vals[i] << 4) | vals[i + 1] for i in range(0, len(vals), 2))
        f.write(f"static const uint8_t UI_{label}_HANGUL[{len(blob)}] PROGMEM = {{\n")
        for i in range(0, len(blob), 32): f.write("  " + ",".join(f"0x{x:02X}" for x in blob[i:i + 32]) + ",\n")
        f.write("};\n"); print(label, len(blob), "bytes")
print(len(chars), "syllables")
